#!/usr/bin/env python3
"""Render the shared monitoring files into Kubernetes ConfigMaps.

``monitoring/`` is the single source of truth for the Grafana datasource,
dashboard provider, dashboard JSON and Prometheus alert rules (docker-compose
mounts them directly). Kubernetes needs them as ConfigMaps, so run this after
editing any of those files:

    python scripts/sync_k8s_monitoring.py

Add ``--check`` to fail (exit 1) if the generated manifests are out of date.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MON = ROOT / "monitoring"
OUT = ROOT / "k8s" / "monitoring"

HEADER = "# GENERATED by scripts/sync_k8s_monitoring.py from monitoring/ - do not edit by hand.\n"


def configmap(name: str, namespace: str, files: dict) -> str:
    lines = ["apiVersion: v1", "kind: ConfigMap", "metadata:", f"  name: {name}",
             f"  namespace: {namespace}", "data:"]
    for key, path in files.items():
        lines.append(f"  {key}: |")
        for line in path.read_text(encoding="utf-8").rstrip("\n").splitlines():
            lines.append(f"    {line}" if line else "")
    return "\n".join(lines) + "\n"


def render() -> dict:
    ns = "monitoring"
    gf = MON / "grafana"
    return {
        "10-prometheus-alerts-configmap.yaml": HEADER + configmap(
            "prometheus-rules", ns, {"alerts.yml": MON / "prometheus" / "alerts.yml"}),
        "20-grafana-configmaps.yaml": HEADER + "\n---\n".join([
            configmap("grafana-datasources", ns,
                      {"prometheus.yml": gf / "provisioning" / "datasources" / "prometheus.yml"}),
            configmap("grafana-dashboard-provider", ns,
                      {"dashboards.yml": gf / "provisioning" / "dashboards" / "dashboards.yml"}),
            configmap("grafana-dashboards", ns,
                      {"house-predictor.json": gf / "dashboards" / "house-predictor.json"}),
        ]),
    }


def main() -> int:
    outputs = render()
    if "--check" in sys.argv:
        stale = [n for n, text in outputs.items()
                 if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != text]
        if stale:
            print("Out of date (run scripts/sync_k8s_monitoring.py): " + ", ".join(stale))
            return 1
        print("k8s/monitoring ConfigMaps are up to date.")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in outputs.items():
        (OUT / name).write_text(text, encoding="utf-8")
        print(f"wrote k8s/monitoring/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
